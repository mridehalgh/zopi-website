function includesTerm(value: string, terms: string[]) {
  return terms.some((term) => value.includes(term));
}

function getCategory(name: string): PartnerCategory {
  const value = name.toLowerCase();
  if (includesTerm(value, healthcareTerms)) return 'Healthcare';
  if (includesTerm(value, logisticsTerms)) return 'Logistics';
  if (includesTerm(value, wholesaleTerms)) return 'Wholesale';
  if (value.includes('google') || value.includes('toshiba') || value.includes('bmw')) return 'Other';
  return 'Retail';
}

function getRegion(name: string): PartnerRegion {
  const value = ` ${name.toLowerCase()} `;
  if (/\b(usa|us)\b/.test(value)) return 'North America';
  if (includesTerm(value, northAmericaTerms)) return 'North America';
  if (/\b(eu|de|italia|norway|switzerland|europe)\b/.test(value)) return 'Europe';
  if (includesTerm(value, ukIrelandTerms)) return 'UK & Ireland';
  return 'Global';
}

function canonicalName(name: string) {
  return canonicalAliases[name] ?? name;
}

function logoFileName(name: string) {
  return name
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');
}

const canonicalPartnerNames = [...new Set(partnerNames.map(canonicalName))];

export const partners = canonicalPartnerNames
  .sort((a, b) => a.localeCompare(b, 'en-GB'))
  .map((name) => ({
    name,
    category: getCategory(name),
    region: getRegion(name),
    letter: name.charAt(0).toUpperCase(),
    aliases: partnerNames.filter((candidate) => canonicalName(candidate) === name && candidate !== name),
    logoName: logoIdentifiers[name] ?? `name:${name}`,
    logoPath: `/logos/partners/${logoFileName(name)}.webp`,
  }));

